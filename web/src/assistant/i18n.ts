export function useAssistantI18n() {
  const { locale } = useI18n()
  const isZh = locale === 'zh'
  const table = isZh ? zh : en
  return {
    locale,
    t: (key: AssistantKey, params?: Record<string, string>) => {
      let text: string = table[key]
      if (params) {
        for (const [name, value] of Object.entries(params)) {
          text = text.split(`{${name}}`).join(value)
        }
      }
      return text
    },
    stageLabel: (id: string) =>
      (isZh ? STAGE_NAMES.zh : STAGE_NAMES.en)[id as keyof typeof STAGE_NAMES.en] ?? id,
    roleLabel: (id: string) =>
      (isZh ? ROLE_NAMES.zh : ROLE_NAMES.en)[id as keyof typeof ROLE_NAMES.en] ?? id,
    gateLabel: (id: string) =>
      (isZh ? GATE_NAMES.zh : GATE_NAMES.en)[id as keyof typeof GATE_NAMES.en] ?? id,
    artifactLabel: (id: string) =>
      (isZh ? ARTIFACT_NAMES.zh : ARTIFACT_NAMES.en)[
        id as keyof typeof ARTIFACT_NAMES.en
      ] ?? id,
    statusLabel: (status: string) =>
      ({
        created: table.statusCreated,
        running: table.statusRunning,
        waiting_gate: table.statusWaiting,
        completed: table.statusCompleted,
        failed: table.statusFailed,
        cancelled: table.statusCancelled,
      })[status] ?? status,
  }
}
